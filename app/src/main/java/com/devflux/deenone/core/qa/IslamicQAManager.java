    public List<QAItem> searchQA(String query, String categoryFilter) {
        List<QAItem> results = new ArrayList<>();
        String q = (query != null) ? query.trim().toLowerCase() : "";

        for (QAItem item : database) {
            boolean matchesCategory = (categoryFilter == null || categoryFilter.isEmpty() ||
                    "সকল".equalsIgnoreCase(categoryFilter) || item.category.equalsIgnoreCase(categoryFilter));

            if (!matchesCategory) continue;

            if (q.isEmpty()) {
                results.add(item);
            } else {
                if (item.question.toLowerCase().contains(q) ||
                        item.answer.toLowerCase().contains(q) ||
                        item.category.toLowerCase().contains(q) ||
                        item.scholarOrInstitution.toLowerCase().contains(q) ||
                        item.reference.toLowerCase().contains(q)) {
                    results.add(item);
                }
            }
        }
        return results;
    }

    public List<QAItem> getAllQA() {
        return new ArrayList<>(database);
    }
